-- A show is one performance of an event at a venue and time.
CREATE TABLE shows (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(200)             NOT NULL,
    venue      VARCHAR(200)             NOT NULL,
    starts_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Every show has its own seats, so a seat id already says which show it belongs to.
-- status + version: the seat row is flipped to SOLD with optimistic locking when a booking is paid.
CREATE TABLE seats (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id      BIGINT      NOT NULL REFERENCES shows (id),
    row_label    VARCHAR(2)  NOT NULL,
    seat_number  INT         NOT NULL,
    price_cents  INT         NOT NULL,
    status       VARCHAR(10) DEFAULT 'AVAILABLE' NOT NULL,
    version      BIGINT      DEFAULT 0 NOT NULL,
    CONSTRAINT uq_seat_position UNIQUE (show_id, row_label, seat_number),
    CONSTRAINT ck_seat_price CHECK (price_cents >= 0),
    CONSTRAINT ck_seat_status CHECK (status IN ('AVAILABLE', 'SOLD'))
);

-- A paid booking by a guest (one or more seats of one show).
-- The idempotency key comes from the browser: paying twice with the same key returns the same booking.
CREATE TABLE bookings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id          BIGINT                   NOT NULL REFERENCES shows (id),
    guest_id         VARCHAR(36)              NOT NULL,
    idempotency_key  VARCHAR(64)              NOT NULL,
    total_cents      INT                      NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_booking_idempotency_key UNIQUE (idempotency_key)
);

CREATE INDEX idx_bookings_guest ON bookings (guest_id);

-- Which seats a booking bought. seat_id is the primary key, so a seat can be in at most one booking:
-- the last line of defence against double booking. Even if two requests get past every other check,
-- the database refuses to sell the same seat twice.
CREATE TABLE booking_seats (
    seat_id     BIGINT NOT NULL PRIMARY KEY REFERENCES seats (id),
    booking_id  BIGINT NOT NULL REFERENCES bookings (id)
);

CREATE INDEX idx_booking_seats_booking ON booking_seats (booking_id);
